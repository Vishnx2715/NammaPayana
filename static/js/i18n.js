  init() {
    this.applyLanguage(this.currentLang);

    // Bind dropdown button with stopPropagation to prevent double toggle
    const dropBtn = document.getElementById('lang-dropdown-btn');
    if (dropBtn) {
      dropBtn.addEventListener('click', (e) => {
        e.preventDefault();
        e.stopPropagation();
        this.toggleDropdown();
      });
    }

    // Bind all language options
    document.querySelectorAll('.lang-opt').forEach(opt => {
      opt.addEventListener('click', (e) => {
        e.preventDefault();
        e.stopPropagation();
        const lang = opt.getAttribute('data-lang');
        if (lang) this.setLanguage(lang);
      });
    });

    // Close dropdown on outside click
    document.addEventListener('click', (e) => {
      if (!e.target.closest('.lang-dropdown-wrap')) {
        this.closeDropdown();
      }
    });
  },

  toggleDropdown() {
    const menu = document.getElementById('lang-dropdown-menu');
    if (menu) menu.classList.toggle('open');
  },

  closeDropdown() {
    const menu = document.getElementById('lang-dropdown-menu');
    if (menu) menu.classList.remove('open');
  },

  setLanguage(lang) {
    this.currentLang = lang;
    localStorage.setItem('np_language', lang);
    this.closeDropdown();
    this.applyLanguage(lang);

    // Toast in the chosen language
    if (typeof App !== 'undefined' && App.toast) {
      const toastMsgs = {
        kn: 'ಭಾಷೆಯನ್ನು ಕನ್ನಡಕ್ಕೆ ಬದಲಿಸಲಾಗಿದೆ 💛',
        hi: 'भाषा हिन्दी में बदल गई 🎉',
        ml: 'ഭാഷ മലയാളത്തിലേക്ക് മാറ്റി 🎉',
        ta: 'மொழி தமிழுக்கு மாறியது 🎉',
        te: 'భాష తెలుగుకు మార్చబడింది 🎉',
        en: 'Language switched to English 🌐'
      };
      App.toast(toastMsgs[lang] || 'Language changed.', 'ok');
    }
  },

  applyLanguage(lang) {
    document.documentElement.lang = lang;

    // Remove all lang body classes, add current
    this.LANG_BODY_CLASS.forEach(c => document.body.classList.remove(c));
    document.body.classList.add(`lang-${lang}`);

    // Update dropdown button label
    const dropBtn = document.getElementById('lang-dropdown-btn-label');
    if (dropBtn) {
      const meta = this.LANG_META[lang] || this.LANG_META.en;
      dropBtn.textContent = meta.label;
    }

    // Mark active option
    document.querySelectorAll('.lang-opt').forEach(opt => {
      opt.classList.toggle('active', opt.getAttribute('data-lang') === lang);
    });

    // Legacy toggle button support (if still in DOM)
    const toggleBtn = document.getElementById('lang-toggle-btn');
    if (toggleBtn) toggleBtn.style.display = 'none';

    // Update all elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const val = this.t(key);
      if (val) {
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
          el.value = val;
        } else {
          el.innerHTML = val;
        }
      }
    });

    // Update placeholders
    document.querySelectorAll('[data-i18n-ph]').forEach(el => {
      const val = this.t(el.getAttribute('data-i18n-ph'));
      if (val) el.setAttribute('placeholder', val);
    });

    // Update titles
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const val = this.t(el.getAttribute('data-i18n-title'));
      if (val) el.setAttribute('title', val);
    });

    // Re-render dynamic components
    if (typeof App !== 'undefined') {
      if (typeof App.initEstimator === 'function') {
        const cityEl = document.getElementById('est-city');
        if (cityEl) cityEl.dispatchEvent(new Event('change'));
      }
      if (App.allDestinations && App.allDestinations.length > 0) {
        const activeTab = document.querySelector('.region-tab-btn.active');
        const regionName = activeTab ? activeTab.getAttribute('data-region') || 'North Karnataka' : 'North Karnataka';
        App.renderRegionCards(regionName);
        if (typeof App.renderPopularDestinations === 'function') App.renderPopularDestinations();
        if (App.isMustVisitPickerOpen && typeof App.renderMustVisitPicker === 'function') App.renderMustVisitPicker();
      }
      if (typeof App.renderStep === 'function') App.renderStep(App.currentStep);
      if (typeof App.updateMustVisitDisplay === 'function') App.updateMustVisitDisplay();
      if (typeof App.loadSavedTripList === 'function') App.loadSavedTripList();
      if (App.activeTrip && typeof App.renderResults === 'function') App.renderResults();
    }

    if (typeof KarnatakaMap !== 'undefined' && KarnatakaMap.isInitialized) {
      KarnatakaMap.applyFilters();
    }

    if (typeof KannadaCompanion !== 'undefined') {
      if (KannadaCompanion.allPhrases && KannadaCompanion.allPhrases.length > 0) {
        KannadaCompanion.renderPhrases(KannadaCompanion.allPhrases);
      }
      if (KannadaCompanion.dialogues && KannadaCompanion.dialogues.length > 0) {
        KannadaCompanion.renderDialogue();
      }
      if (KannadaCompanion.lastTranslatedResult) {
        KannadaCompanion.renderTranslationResult(KannadaCompanion.lastTranslatedResult);
      }
      const sourceLangSelect = document.getElementById('kc-source-lang');
      if (sourceLangSelect && lang !== 'kn') {
        sourceLangSelect.value = lang;
      }
    }
  }
