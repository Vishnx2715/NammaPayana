/**
 * XSS-safe HTML escaper. Escapes &, <, >, ", and ' characters.
 * Must be called on every API-sourced string inserted via innerHTML.
 * Defined here (first app script loaded) so map.js, phrases.js, auth.js, and app.js can use it.
 * @param {*} str - Value to escape (coerced to string).
 * @returns {string} HTML-safe string.
 */
function escapeHtml(str) {
  if (str === null || str === undefined) return '';
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#x27;');
}

